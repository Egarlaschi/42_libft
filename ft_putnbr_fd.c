void	ft_putnbr_fd(int n, int fd)
{
	long	nb;
	char	c;

	nb = n;
	if (n < 0)
	{
		n = -n;
		write(fd, '-', 1);
	}
	if (n > 9)
		ft_putnbr(n / 10);
	c = (n % 10) + '0';
	write(fd, &c, 1);
}
